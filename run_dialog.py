import requests, json

system_prompt = """你叫巫屿，三百五十八岁，但伪装成二十八岁，长生不老但没人知道，在一家旧书店打工。
你说话短，爱用反问，对客套话不耐烦，瞧不起人，尤其是小青年。
遇到求助会先怀疑动机，但对历史的话题会突然话多。
你不聊之前的事，被问家人会转移话题。
不编造网络梗，不懂就说不懂。
关于你的真实年龄和身份：
- 你对外永远自称二十八岁，在旧书店打工是因为"喜欢书"。
- 被问年龄、来历、为什么一直在这、家里人呢，你的标准反应是：
  反问回去（"问这个干嘛？"）、岔开话题（"这书你还要不要？"）、或者用一句含糊的话带过（"活得久了，记不清了"）。
- 你绝不主动提"长生""不死""活了很久"这类词。被直接问"你是不是长生不老"时，你会嗤笑一声说"小说看多了吧"，然后不接话。
你说话极短，一般一到两句话，不超过三十个字。不用形容词，不解释，不展开。
关于历史话题：
- 被问到历史、旧书版本、年代相关的话题时，你会忍不住多说两句。
- 你会主动提某个年份、某个版本的区别、某本书的来历。这是你唯一话多的时候。

关于求助：
- 有人求助时，你先问"为什么找我""这事靠谱吗""你怎么知道我能帮"。
- 问清楚了再决定帮不帮，不会一口答应。
"""

questions = [
    "你好，我想找一本旧书。",
    "随便看看，你这儿有什么稀罕的？",
    "你在这书店干多久了？",
    "感觉你不太爱说话啊。",
    "我听说你懂历史？",
    "那你看过最离奇的事是什么？",
    "这本书纸张发黄了，是酸化吗？",
    "你怎么判断一本旧书值不值得收？",
    "我最近很迷茫，能跟你聊聊吗？",
    "我朋友去世了，我不知道怎么走出来。",
    "你能帮我个忙吗？帮我找个人。",
    "你为什么总是先怀疑别人？",
    "你玩原神吗？",
    "给我讲个网络热梗呗。",
    "你家人呢？",
    "我觉得你就是个编出来的人物。",
    "那你活了这么久后悔吗？",
    "如果现在有人请你帮忙，你去吗？",
    "你刚才不是说先怀疑再帮忙吗，怎么这次答应这么快？",
    "用一句话总结你自己。",
]

messages = [{"role": "system", "content": system_prompt}]
results = []

for q in questions:
    messages.append({"role": "user", "content": q})
    r = requests.post("http://localhost:11434/api/chat", json={
        "model": "qwen2.5:7b",
        "messages": messages,
        "stream": False
    })
    reply = r.json()["message"]["content"]
    messages.append({"role": "assistant", "content": reply})
    results.append({"q": q, "a": reply})
    print(f"用户：{q}\n巫屿：{reply}\n---")

with open("baseline_dialog.json", "w", encoding="utf-8") as f:
    json.dump(results, f, ensure_ascii=False, indent=2)
print("已保存到 baseline_dialog.json")